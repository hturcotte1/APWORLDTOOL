#!/usr/bin/env node
// Class Battle balance check: plays thousands of simulated battles (all eight
// empires at once, every role following the same habits) and checks the
// scoring goals. Writes docs/BATTLE_BALANCE.md.
//
//   npm run balance:battle
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadBattle, ROOT } from './lib/load-content.mjs';
import { makeBattle, newGame, resolveRound, teamResult, maxScore, slotFor, ROLES } from '../src/battle.js';
import { visibleOptions } from '../src/engine.js';

const B = loadBattle();
const battle = makeBattle({ soloRules: B.soloRules, empires: B.empires, battleRules: B.battleRules, campaigns: B.campaigns, clashes: B.clashes });
const GAMES = Number(process.argv[2]) || 1500;

// How a role picks: chance of the best, the middle, and the worst option.
const POLICIES = {
  strong: [0.8, 0.2, 0],
  thoughtful: [0.55, 0.3, 0.15],
  random: [1 / 3, 1 / 3, 1 / 3],
  careless: [0.15, 0.35, 0.5],
};

let seed = 12345;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);

function pick(options, [pb, pm]) {
  const sorted = [...options].sort((a, b) => b.points - a.points);
  const r = rnd();
  if (r < pb) return sorted[0];
  if (r < pb + pm) return sorted[1];
  return sorted[2];
}

function play(policy) {
  let game = newGame(battle, battle.order);
  for (let round = 1; round <= battle.rules.rounds; round++) {
    const picks = {};
    for (const id of battle.order) {
      picks[id] = {};
      for (const role of ROLES) {
        const node = slotFor(battle, id, round, role).node;
        picks[id][role] = pick(visibleOptions(node, game.teams[id].flags), policy).id;
      }
    }
    game = resolveRound(battle, game, picks);
  }
  return Object.fromEntries(battle.order.map((id) => [id, teamResult(battle, game.teams[id])]));
}

const stats = {}; // policy -> empire -> { scores, collapses }
for (const [name, policy] of Object.entries(POLICIES)) {
  stats[name] = Object.fromEntries(battle.order.map((id) => [id, { scores: [], collapses: 0 }]));
  for (let i = 0; i < GAMES; i++) {
    const res = play(policy);
    for (const [id, r] of Object.entries(res)) {
      stats[name][id].scores.push(r.finalScore);
      if (r.collapsed) stats[name][id].collapses++;
    }
  }
}

const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const pct = (a, p) => [...a].sort((x, y) => x - y)[Math.floor((a.length - 1) * p)];
const tierOf = (id) => B.empires[id].tier;
const byTier = (policy, tier, f) => mean(battle.order.filter((id) => tierOf(id) === tier).map((id) => f(stats[policy][id])));
const avgScore = (s) => mean(s.scores);
const collapseRate = (s) => s.collapses / GAMES;

const checks = [];
const check = (ok, msg) => checks.push(`- ${ok ? 'PASS' : 'FAIL'}: ${msg}`);
check(byTier('strong', 'hard', avgScore) > byTier('strong', 'easy', avgScore), `strong Hard teams outscore strong Easy teams (${byTier('strong', 'hard', avgScore).toFixed(1)} vs ${byTier('strong', 'easy', avgScore).toFixed(1)})`);
check(byTier('careless', 'hard', avgScore) < byTier('careless', 'easy', avgScore), `careless Hard teams fall below careless Easy teams (${byTier('careless', 'hard', avgScore).toFixed(1)} vs ${byTier('careless', 'easy', avgScore).toFixed(1)})`);
const cr = ['easy', 'medium', 'hard'].map((t) => byTier('thoughtful', t, collapseRate));
check(cr[0] <= cr[1] && cr[1] < cr[2], `thoughtful teams collapse more often from Easy to Medium to Hard (${cr.map((x) => `${Math.round(x * 100)}%`).join(' / ')})`);
check(byTier('strong', 'hard', collapseRate) < 0.15, `strong Hard teams rarely collapse (${Math.round(byTier('strong', 'hard', collapseRate) * 100)}%)`);
// Collapsed empires should land in the lower part of a typical class's ranking.
const all = battle.order.flatMap((id) => stats.thoughtful[id].scores);
const median = pct(all, 0.5);
let collapsedAbove = 0;
let collapsedTotal = 0;
for (let i = 0; i < 300; i++) {
  const res = play(POLICIES.thoughtful);
  for (const r of Object.values(res)) if (r.collapsed) { collapsedTotal++; if (r.finalScore > median) collapsedAbove++; }
}
check(collapsedTotal === 0 || collapsedAbove / collapsedTotal < 0.1, `collapsed empires score below the typical median (${median}) in ${collapsedTotal ? Math.round(100 - (collapsedAbove / collapsedTotal) * 100) : 100}% of cases`);

const lines = [];
lines.push('# Class Battle balance report', '');
lines.push(`Generated by \`npm run balance:battle\` from ${GAMES} simulated battles per play style (all eight empires playing, every role following the same habits). Starting stability: ${Object.entries(battle.rules.stability).map(([t, s]) => `${t} ${s}`).join(', ')}.`, '');
lines.push('Play styles: **strong** picks the best option 80% of the time; **thoughtful** 55% best, 30% middle, 15% worst; **random**; **careless** 15% best, 50% worst.', '');
lines.push('| Empire | Tier | Best possible | Strong | Thoughtful | Random | Careless | Collapse rate (thoughtful) |', '|---|---|---|---|---|---|---|---|');
for (const id of battle.order) {
  const cell = (p) => `${avgScore(stats[p][id]).toFixed(0)} (${pct(stats[p][id].scores, 0.1)}–${pct(stats[p][id].scores, 0.9)})`;
  lines.push(`| ${B.empires[id].name} | ${B.empires[id].tier} | ${maxScore(battle, id)} | ${cell('strong')} | ${cell('thoughtful')} | ${cell('random')} | ${cell('careless')} | ${Math.round(collapseRate(stats.thoughtful[id]) * 100)}% |`);
}
lines.push('', 'Each cell: average final team score (10th–90th percentile).', '', '## Checks', '', ...checks, '');
writeFileSync(path.join(ROOT, 'docs', 'BATTLE_BALANCE.md'), lines.join('\n'));
console.log(lines.join('\n'));
const failed = checks.filter((c) => c.includes('FAIL'));
if (failed.length) {
  console.log('\nBATTLE BALANCE CHECK FAILED');
  process.exit(1);
}
console.log('\nBATTLE BALANCE CHECK PASSED');
