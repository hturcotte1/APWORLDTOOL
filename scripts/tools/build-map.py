#!/usr/bin/env python3
"""Builds public/map-data.js: a simplified world-land outline as one SVG path.

Source: Natural Earth 1:50m land (public domain, naturalearthdata.com).
Projection: plate carree (equirectangular), the projection of many early
modern charts. Usage: python3 scripts/tools/build-map.py ne_50m_land.geojson
"""
import json, sys, math

LON0, LON1, LAT0, LAT1, S = -130.0, 165.0, -45.0, 75.0, 4.0   # degrees, px per degree
TOL = 0.55  # simplification tolerance in px

def proj(lon, lat):
    return ((lon - LON0) * S, (LAT1 - lat) * S)

def dp(pts, tol):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    den = math.hypot(dx, dy) or 1e-9
    imax, dmax = 0, -1
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / den
        if d > dmax: imax, dmax = i, d
    if dmax <= tol: return [pts[0], pts[-1]]
    return dp(pts[:imax + 1], tol)[:-1] + dp(pts[imax:], tol)

def ring_area(pts):
    return abs(sum(pts[i][0] * pts[i - 1][1] - pts[i - 1][0] * pts[i][1] for i in range(len(pts)))) / 2

src = json.load(open(sys.argv[1]))
parts = []
for f in src['features']:
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for poly in polys:
        for ring in poly[:1]:  # outer rings only
            lons = [p[0] for p in ring]; lats = [p[1] for p in ring]
            if max(lats) < -58: continue                      # Antarctica
            if max(lons) < LON0 - 5 or min(lons) > LON1 + 5: continue
            if max(lats) < LAT0 - 5 or min(lats) > LAT1 + 5: continue
            pts = [proj(lon, lat) for lon, lat in ring]
            if ring_area(pts) < 6: continue                   # tiny islands
            # split the ring in two halves so Douglas-Peucker keeps closed shapes
            mid = len(pts) // 2
            simp = dp(pts[:mid + 1], TOL)[:-1] + dp(pts[mid:], TOL)
            if len(simp) < 4: continue
            d = 'M' + ' '.join(f'{x:.1f} {y:.1f}' for x, y in simp) + 'Z'
            parts.append(d.replace('.0 ', ' ').replace('.0Z', 'Z'))
path = ''.join(parts)
W, H = (LON1 - LON0) * S, (LAT1 - LAT0) * S
out = f"""// Generated by scripts/tools/build-map.py from Natural Earth 1:50m land
// (public domain, https://www.naturalearthdata.com). Plate carree projection.
export const MAP = {{ lon0: {LON0}, lon1: {LON1}, lat0: {LAT0}, lat1: {LAT1}, scale: {S}, width: {W:.0f}, height: {H:.0f} }};
export const project = (lon, lat) => [(lon - MAP.lon0) * MAP.scale, (MAP.lat1 - lat) * MAP.scale];
export const LAND = '{path}';
"""
open('public/map-data.js', 'w').write(out)
print(f'{len(parts)} shapes, {len(path)/1024:.1f} KB path, viewBox 0 0 {W:.0f} {H:.0f}')
