#!/usr/bin/env python3
"""Builds public/river-data.js: major rivers as one SVG path, drawn on the
turning-point map scenes (the Niger, the Volga, the Ganges, and so on).

Source: Natural Earth 1:50m rivers and lake centerlines (public domain,
naturalearthdata.com). Same plate carree projection as public/map-data.js.
Usage: python3 scripts/tools/build-rivers.py ne_50m_rivers_lake_centerlines.geojson
"""
import json, sys, math

LON0, LON1, LAT0, LAT1, S = -130.0, 165.0, -45.0, 75.0, 4.0   # must match build-map.py
TOL = 0.25  # simplification tolerance in px

# Rivers that matter to the eight empires' stories.
RIVERS = {
    'Niger', 'Volga', 'Kama', 'Don', 'Dnepre', 'Indus', 'Chenab', 'Sutlej', 'Ganges', 'Yamuna',
    'Brahmaputra', 'Narmada', 'Krishna', 'Danube', 'Tigris', 'Euphrates', 'Shatt al Arab', 'Nile',
    'Yangtze', 'Huang', 'Amu  Darya', 'Syr Darya', 'Amur', 'Rhine', 'Elbe', 'Vistula', 'Tajo',
    'Mississippi', 'Rio Grande', 'Amazonas', 'Orinoco',
}

def proj(lon, lat):
    return ((lon - LON0) * S, (LAT1 - lat) * S)

def dp(pts, tol):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    den = math.hypot(dx, dy) or 1e-9
    imax, dmax = 0, -1
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / den
        if d > dmax: imax, dmax = i, d
    if dmax <= tol: return [pts[0], pts[-1]]
    return dp(pts[:imax + 1], tol)[:-1] + dp(pts[imax:], tol)

src = json.load(open(sys.argv[1]))
parts, found = [], set()
for f in src['features']:
    name = f['properties'].get('name') or ''
    if name not in RIVERS: continue
    g = f['geometry']
    lines = g['coordinates'] if g['type'] == 'MultiLineString' else [g['coordinates']]
    for line in lines:
        pts = [proj(lon, lat) for lon, lat in line if LON0 <= lon <= LON1 and LAT0 <= lat <= LAT1]
        pts = dp(pts, TOL)
        if len(pts) < 2: continue
        found.add(name)
        parts.append('M' + ' '.join(f'{x:.1f} {y:.1f}' for x, y in pts))

missing = RIVERS - found
if missing: sys.exit(f'rivers not found: {sorted(missing)}')
out = ('// Generated by scripts/tools/build-rivers.py from Natural Earth 1:50m rivers\n'
       '// (public domain, https://www.naturalearthdata.com). Plate carree projection.\n'
       f"export const RIVERS = '{''.join(parts)}';\n")
open('public/river-data.js', 'w').write(out)
print(f'{len(found)} rivers, {len(parts)} lines, {len(out) // 1024} KB')
